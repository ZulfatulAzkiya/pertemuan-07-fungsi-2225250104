
def luas_persegi_panjang(panjang, lebar):
    return panjang * lebar


print("Luas persegi panjang:")
print("Panjang = 8, Lebar = 5,", 
      "Luas =", luas_persegi_panjang(8, 5))
print("Panjang = 2.5, Lebar = 4,",
      "Luas =", luas_persegi_panjang(2.5, 4))
print("Panjang = 0, Lebar = 7,",
      "Luas =", luas_persegi_panjang(0, 7))
